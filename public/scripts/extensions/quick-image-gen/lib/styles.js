export function applyQuickImageStyle(prompt, styleId) {
    const style = Object.hasOwn(QIG_STYLES, styleId) ? QIG_STYLES[styleId] : null;
    return style && styleId !== 'none' ? `${style.prefix}${prompt}${style.suffix}` : prompt;
}

import fs from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const names = ['wandButton', 'wandMenu', 'help', 'hotkeys', 'formatting', 'welcome', 'welcomePrompt', 'assistantNote', 'welcomePanelOnboarding'];
const templates = Object.fromEntries(await Promise.all(names.map(async name => [
    `/scripts/templates/${name}.html`,
    await fs.readFile(new URL(`public/scripts/templates/${name}.html`, root), 'utf8'),
])));
const output = new URL('public/scripts/startup-templates.js', root);
const quote = value => `'${JSON.stringify(value).slice(1, -1).replaceAll('\\"', '"').replaceAll('\'', '\\\'')}'`;
const entries = Object.entries(templates).map(([name, source]) => `    ${quote(name)}: ${quote(source)},`);
const text = `// Generated by scripts/build-startup-templates.js. Edit the source HTML templates.\nexport const startupTemplates = {\n${entries.join('\n')}\n};\n`;
if (process.argv.includes('--check')) {
    if (await fs.readFile(output, 'utf8').catch(() => '') !== text) {
        console.error('Startup templates are out of date. Run node scripts/build-startup-templates.js.');
        process.exitCode = 1;
    }
} else {
    await fs.writeFile(output, text);
}

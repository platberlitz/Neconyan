/** Refresh the theme baseline and catalogue from the bundled agent templates. */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const templates = new URL('../public/scripts/extensions/in-chat-agents/templates/', import.meta.url);
const output = new URL('../public/scripts/extensions/third-party/Neconyan-Regex-Agent-Themes/src/', import.meta.url);
const read = name => JSON.parse(readFileSync(new URL(name, templates), 'utf8'));
const bundles = read('regex-bundles.json');
const groups = read('groups.json');
const families = {};
for (const [groupId, family] of [['grp-pura-trackers', 'pura'], ['grp-pura-ethereality-trackers', 'ethereal']]) {
    for (const id of groups.find(group => group.id === groupId).agentTemplateIds) families[id] = family;
}
const ids = [...Object.keys(families), 'tpl-chat-only-companion', 'tpl-chatroom-companion', 'tpl-message-inbox-companion'];
const labels = {};
const stock = [];
for (const templateId of ids) {
    const file = `${templateId.slice(4)}.json`;
    const template = read(file);
    labels[templateId] = template.name;
    for (const script of bundles[templateId] ?? template.regexScripts ?? []) {
        const match = script.findRegex.match(/^\/(.*)\/([a-z]*)$/s);
        const regex = match ? new RegExp(match[1], match[2]) : new RegExp(script.findRegex);
        stock.push({
            templateId, scriptId: script.id, scriptName: script.scriptName,
            family: families[templateId] ? 'tracker' : 'companion',
            source: bundles[templateId] ? 'regex-bundles.json' : file,
            findRegex: script.findRegex,
            groups: new RegExp(`${regex.source}|`, regex.flags.replace(/[gy]/g, '')).exec('').length - 1,
            flags: regex.flags, delimited: Boolean(match), replaceString: script.replaceString ?? '',
            placement: script.placement ?? [2], markdownOnly: Boolean(script.markdownOnly),
            promptOnly: Boolean(script.promptOnly), minDepth: script.minDepth ?? null, maxDepth: script.maxDepth ?? null,
        });
    }
}
const header = '/** GENERATED by scripts/build-regex-agent-themes-stock.js. Do not edit by hand. */\n\n';
const files = {
    'stock.js': `${header}export const STOCK = ${JSON.stringify(stock, null, 4)};

export function stockKey(templateId, scriptId) {
    return \`\${templateId}/\${scriptId}\`;
}

export const STOCK_BY_KEY = new Map(STOCK.map(item => [stockKey(item.templateId, item.scriptId), item]));
export const STOCK_REPLACE_STRINGS = new Set(STOCK.map(item => item.replaceString));

export function getStock(templateId, scriptId) {
    return STOCK_BY_KEY.get(stockKey(templateId, scriptId)) ?? null;
}
`,
    'template-catalog.js': `${header}export const TEMPLATE_LABELS = Object.freeze(${JSON.stringify(labels, null, 4)});

export const TRACKER_FAMILIES = Object.freeze(${JSON.stringify(families, null, 4)});
`,
};
for (const [name, content] of Object.entries(files)) {
    const path = new URL(name, output);
    if (process.argv.includes('--check')) {
        if (readFileSync(path, 'utf8') !== content) throw new Error(`Refresh ${fileURLToPath(path)}`);
    } else {
        writeFileSync(path, content);
    }
}
console.log(`Regex Agent Themes: ${ids.length} templates, ${stock.length} scripts`);

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { icons, aliases, renderIcon } from './catline-icons.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
const outputs = new Map();
const variables = [];
const plainVariables = [];
const classes = [];
const catalogue = [];
const names = new Set();
const spriteDrawings = [];

for (const [name, drawings] of Object.entries(icons).sort(([a], [b]) => a.localeCompare(b))) {
    const variants = drawings.map((drawing, index) => {
        const svg = renderIcon(drawing);
        const filename = `${name}${index ? '-plain' : ''}.svg`;
        outputs.set(`public/img/icons/catline/${filename}`, svg);
        const id = filename.slice(0, -4);
        spriteDrawings.push(`<g class="icon" id="${id}">${svg}</g>`);
        return `url('../img/icons/catline/sprite.svg?v=SPRITE_HASH#${id}')`;
    });
    variables.push(`--neco-svg-${name}:${variants[0]};`);
    plainVariables.push(`--neco-svg-${name}:${variants[1]};`);
    const group = [name, ...(aliases[name] ?? [])].map(item => `fa-${item}`);
    for (const alias of group) {
        if (names.has(alias)) throw new Error(`Duplicate icon alias: ${alias}`);
        names.add(alias);
    }
    catalogue.push(group);
    classes.push(`${group.map(alias => `.${alias}`).join(',')} { --neco-icon: var(--neco-svg-${name}); }`);
}
for (const name of Object.keys(aliases)) {
    if (!icons[name]) throw new Error(`Missing icon: ${name}`);
}

// Only the fragment's drawing is painted; the other icons add no off-screen work.
const sprite = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24"><style>.icon{display:none}.icon:target{display:inline}</style>${spriteDrawings.join('')}</svg>\n`;
const spriteHash = createHash('sha256').update(sprite).digest('hex').slice(0, 10);
outputs.set('public/img/icons/catline/sprite.svg', sprite);
outputs.set('public/css/neconyan-icons-map.css', `/* Generated by scripts/build-catline-icons.js. Edit scripts/catline-icons.js. */
:root {
${variables.join('\n')}
}
:root[data-sb-kittyless='true'] {
${plainVariables.join('\n')}
}
${classes.join('\n')}
`.replaceAll('SPRITE_HASH', spriteHash));
outputs.set('public/img/icons/catline/catalogue.json', JSON.stringify(catalogue) + '\n');

let stale = false;
for (const [filename, text] of outputs) {
    const target = path.join(root, filename);
    if (check) {
        if (await fs.readFile(target, 'utf8').catch(() => null) !== text) {
            console.error(`Outdated Catline asset: ${filename}`);
            stale = true;
        }
    } else {
        await fs.mkdir(path.dirname(target), { recursive: true });
        await fs.writeFile(target, text);
    }
}
if (stale) process.exitCode = 1;
else console.log(`Catline: ${catalogue.length} drawings, ${names.size} compatible names${check ? ' checked' : ' built'}.`);
